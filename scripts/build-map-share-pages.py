def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Check published pages match their source')
    args = parser.parse_args()
    cards = [*EXPLORE_CARDS, *monument_cards()]
    for card in cards:
        path = PUBLIC / (card['path'].lstrip('/') + '.html')
        rendered = render_page(card)
        if args.check:
            if not path.is_file() or path.read_text() != rendered:
                raise SystemExit(f'{path.relative_to(ROOT)} needs regeneration')
            image = PUBLIC / card['image'].lstrip('/')
            if not image.is_file() or image.read_bytes()[:3] != b'\xff\xd8\xff':
                raise SystemExit(f'{image.relative_to(ROOT)} is missing or is not a JPEG')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered)
    print(f'{"Checked" if args.check else "Built"} {len(cards)} map share pages.')


if __name__ == '__main__':
    main()
