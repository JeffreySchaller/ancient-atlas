import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../public/assets/js/analytics.js', import.meta.url), 'utf8');
function setup({ hostname = 'theancientatlas.com', choice, gpc = false } = {}) {
 const scripts = [], storage = new Map(choice ? [['atlas-analytics-v1', choice]] : []), navigation = [];
 const button = choice => ({ dataset: { choice }, focus() {}, addEventListener(_, fn) { this.click = fn; } });
 const allow = button('granted'), deny = button('denied'), paragraph = {};
 const panel = { setAttribute() {}, querySelector(s) { return s === 'p' ? paragraph : s.includes('denied') ? deny : allow; }, querySelectorAll() { return [allow, deny]; } };
 const settings = button();
 const document = { referrer: 'https://example.com/private?email=secret', createElement(tag) { return tag === 'section' ? panel : tag === 'button' ? settings : {}; }, head: { appendChild(el) { if (el.src) scripts.push(el); } }, body: { appendChild() {} } };
 const location = { hostname, origin: 'https://' + hostname, pathname: '/', search: '?utm_source=google&email=private%40example.com&site=private', reload() { navigation.push('reload'); } };
 const window = {};
 vm.runInNewContext(source, { window, document, location, navigator: { globalPrivacyControl: gpc }, localStorage: { getItem: k => storage.get(k) || null, setItem: (k,v) => storage.set(k,v) }, URL, URLSearchParams });
 return { scripts, panel, allow, deny, window, navigation, commands: () => Array.from(window.dataLayer || [], args => Array.from(args)) };
}
const fresh = setup();
assert.equal(fresh.scripts.length, 0);
assert.equal(fresh.panel.hidden, false);
fresh.window.atlasAnalytics('atlas_site_view', 'Giza');
assert.equal(fresh.commands().length, 0);
fresh.deny.click();
assert.equal(fresh.scripts.length, 0);
const accepted = setup();
accepted.allow.click();
assert.equal(accepted.scripts.length, 1);
const config = accepted.commands().find(c => c[0] === 'config');
assert.equal(config[1], 'G-LZSJ94PNP6');
assert.equal(config[2].allow_google_signals, false);
assert.equal(config[2].allow_ad_personalization_signals, false);
assert.equal(config[2].page_referrer, 'https://example.com/');
assert(!config[2].page_location.includes('private'));
const consent = accepted.commands().filter(c => c[0] === 'consent');
assert.equal(consent[0][2].ad_storage, 'denied');
assert.equal(consent[1][2].analytics_storage, 'granted');
accepted.window.atlasAnalytics('atlas_site_view', 'Giza');
accepted.window.atlasAnalytics('atlas_video_open', 'b7hG-LASJIU');
assert.equal(accepted.commands().filter(c => c[0] === 'event').length, 2);
accepted.window.atlasAnalytics('atlas_video_open', 'not-a-video-id');
accepted.window.atlasAnalytics('unknown', 'secret');
assert.equal(accepted.commands().filter(c => c[0] === 'event').length, 2);
accepted.deny.click();
assert.equal(accepted.commands().at(-1)[2].analytics_storage, 'denied');
assert.equal(accepted.navigation[0], 'reload');
accepted.window.atlasAnalytics('atlas_site_view', 'Giza');
assert.equal(accepted.commands().filter(c => c[0] === 'event').length, 2);
const gpc = setup({ choice: 'granted', gpc: true });
assert.equal(gpc.scripts.length, 0);
gpc.allow.click();
assert.equal(gpc.scripts.length, 0);
assert.equal(setup({ choice: 'granted' }).scripts.length, 1);
assert.equal(setup({ hostname: 'localhost', choice: 'granted' }).scripts.length, 0);
assert.equal(setup({ hostname: 'preview.netlify.app', choice: 'granted' }).scripts.length, 0);
console.log('Analytics checks passed: opt-in, rejection, revocation, GPC, production guard, sanitized URLs, and catalog/video events.');
